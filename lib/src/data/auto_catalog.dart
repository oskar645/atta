List<String> _canonicalizeAutoBrands(Iterable<String> values) {
  final unique = <String>{};
  for (final value in values) {
    final canonical = canonicalAutoBrand(value);
    if (canonical.isEmpty || canonical == kAutoCustomBrandLabel) {
      continue;
    }
    unique.add(canonical);
  }
  return unique.toList();
}

List<String> _buildAutoBrandsPopular() {
  final priority = _canonicalizeAutoBrands(_kAutoBrandsPriorityRaw);
  final prioritySet = priority.toSet();
  final tail = _canonicalizeAutoBrands(<String>[
    ..._kAutoBrandsRequiredTailRaw,
    ...kAutoModels.keys,
  ])
    ..removeWhere(prioritySet.contains)
    ..sort(
      (a, b) => a.toLowerCase().compareTo(b.toLowerCase()),
    );
  return List<String>.unmodifiable(<String>[
    ...priority,
    ...tail,
    kAutoCustomBrandLabel,
  ]);
}

