String canonicalAutoBrand(String? brand) {
  final value = (brand ?? '').trim();
  if (value.isEmpty) return '';
  return kAutoBrandAliases[value.toUpperCase()] ?? value;
}

List<String> autoModelsForBrand(String? brand) {
  final canonical = canonicalAutoBrand(brand);
  final models = kAutoModels[canonical];
  if (models == null || models.isEmpty) {
    return const <String>[kAutoCustomModelLabel];
  }
  return models;
}

List<String> autoGenerationsForBrandModel(String? brand, String? model) {
  final canonicalBrand = canonicalAutoBrand(brand);
  final key = '$canonicalBrand|${(model ?? '').trim()}';
  return kAutoGenerations[key] ?? const <String>[];
}

bool autoBrandMatchesQuery(String brand, String query) {
  final normalizedQuery = query.trim().toLowerCase();
  if (normalizedQuery.isEmpty) return true;
  final candidates = <String>{
    brand,
    canonicalAutoBrand(brand),
  };
  for (final entry in kAutoBrandAliases.entries) {
    if (entry.value == brand) {
      candidates.add(entry.key);
    }
  }
  return candidates.any((item) => item.toLowerCase().contains(normalizedQuery));
}

